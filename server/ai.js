function extractKeyPhrases(text) {
  const lines = text.split('\n').map(l => l.trim()).filter(l => l.length > 5);
  const headings = lines.filter(l => (l.startsWith('#') || (l.length < 60 && !l.endsWith('.'))));
  const bulletPoints = lines.filter(l => l.startsWith('-') || l.startsWith('*') || /^\d+\./.test(l));
  const definitions = lines.filter(l => /is defined as|refers to|means|consists of|is the process/i.test(l));
  
  return {
    headings: headings.slice(0, 10),
    bulletPoints: bulletPoints.slice(0, 20),
    definitions: definitions.slice(0, 10),
    allLines: lines
  };
}

