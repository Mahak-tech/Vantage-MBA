/**
 * Get active Gemini API Key
 */
function getActiveApiKey(customKey) {
  if (customKey && customKey.trim()) return customKey.trim();
  const settings = db.getSettings();
  if (settings.geminiApiKey && settings.geminiApiKey.trim()) return settings.geminiApiKey.trim();
  if (process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY.trim()) return process.env.GEMINI_API_KEY.trim();
  return null;
}

/**
 * Initialize Gemini Model
 */
function getGeminiClient(apiKey) {
  const key = getActiveApiKey(apiKey);
  if (!key) return null;
  return new GoogleGenerativeAI(key);
}

/**
 * Test if an API key is valid
 */
async function testApiKey(apiKey) {
  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: 'gemini-1.5-flash' });
    const result = await model.generateContent('Say "OK" in one word.');
    const response = await result.response;
    const text = response.text();
    return { valid: true, message: 'Gemini API key is valid and working!', text };
  } catch (err) {
    return { valid: false, error: err.message || 'Failed to authenticate with Gemini API' };
  }
}

/**
 * Clean JSON output from LLM
 */
function parseJsonFromLlm(text) {
  try {
    const cleaned = text
      .replace(/```json/gi, '')
      .replace(/```/g, '')
      .trim();
    return JSON.parse(cleaned);
  } catch (e) {
    // Try to extract between first [ and last ] or first { and last }
    const firstBracket = text.indexOf('[');
    const lastBracket = text.lastIndexOf(']');
    if (firstBracket !== -1 && lastBracket !== -1 && lastBracket > firstBracket) {
      try {
        return JSON.parse(text.substring(firstBracket, lastBracket + 1));
      } catch (err) {}
    }

    const firstBrace = text.indexOf('{');
    const lastBrace = text.lastIndexOf('}');
    if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
      try {
        return JSON.parse(text.substring(firstBrace, lastBrace + 1));
      } catch (err) {}
    }
    throw new Error('Could not parse valid JSON from AI response.');
  }
}

